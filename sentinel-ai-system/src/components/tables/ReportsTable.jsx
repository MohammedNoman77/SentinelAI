import { useState, useEffect } from 'react';
import {
  FileText,
  Shield,
  AlertTriangle,
  Users,
  Monitor,
  Lock,
  Database,
  Calendar,
  MoreHorizontal,
} from 'lucide-react';
import { getReports } from '../../services/reportsService';

const typeIcons = {
  Executive: { icon: FileText, color: 'text-cyan-400' },
  Threats: { icon: Shield, color: 'text-red-400' },
  Incidents: { icon: AlertTriangle, color: 'text-orange-400' },
  Behavior: { icon: Users, color: 'text-purple-400' },
  Endpoints: { icon: Monitor, color: 'text-blue-400' },
  Compliance: { icon: Lock, color: 'text-yellow-400' },
};

const statusStyles = {
  completed: 'bg-green-500/20 text-green-400',
  Completed: 'bg-green-500/20 text-green-400',
  generating: 'bg-blue-500/20 text-blue-400',
  Generating: 'bg-blue-500/20 text-blue-400',
  scheduled: 'bg-purple-500/20 text-purple-400',
  Scheduled: 'bg-purple-500/20 text-purple-400',
  failed: 'bg-red-500/20 text-red-400',
};

const ReportsTable = ({ onSelectReport, selectedId }) => {
  const [reports, setReports] = useState([]);
  const [loading, setLoading] = useState(true);
  const [activeTab, setActiveTab] = useState('All Reports');

  const tabs = ['All Reports', 'Scheduled', 'Compliance', 'Custom Reports'];

  useEffect(() => {
    const fetchData = async () => {
      setLoading(true);
      try {
        const params = {};
        if (activeTab === 'Scheduled') params.type = 'Scheduled';
        if (activeTab === 'Compliance') params.type = 'Compliance';

        const result = await getReports(params);
        setReports(result.data.reports);
      } catch (err) {
        console.error('Failed to fetch reports:', err);
      } finally {
        setLoading(false);
      }
    };
    fetchData();
  }, [activeTab]);

  return (
    <div className="bg-sentinel-panel border border-sentinel-border rounded-xl p-6">
      <div className="flex items-center justify-between mb-6">
        <div>
          <h3 className="text-lg font-bold text-white">Reports</h3>
          <p className="text-xs text-sentinel-text-dim mt-1">التقارير الأمنية</p>
        </div>
        <button className="flex items-center gap-2 px-4 py-2 rounded-lg bg-gradient-to-r from-cyan-500 to-blue-600 hover:from-cyan-400 hover:to-blue-500 text-white text-sm font-medium transition-all">
          + Generate Report
        </button>
      </div>

      <div className="flex items-center gap-4 border-b border-sentinel-border mb-4">
        {tabs.map((tab) => (
          <button
            key={tab}
            onClick={() => setActiveTab(tab)}
            className={`pb-3 px-1 text-sm font-medium transition-colors border-b-2 ${
              activeTab === tab
                ? 'text-cyan-400 border-cyan-400'
                : 'text-sentinel-text-dim border-transparent hover:text-white'
            }`}
          >
            {tab}
          </button>
        ))}
      </div>

      {loading ? (
        <div className="h-64 flex items-center justify-center">
          <div className="text-cyan-400 text-sm">Loading reports...</div>
        </div>
      ) : reports.length === 0 ? (
        <div className="h-64 flex items-center justify-center">
          <p className="text-sentinel-text-dim text-sm">لا توجد تقارير</p>
        </div>
      ) : (
        <div className="overflow-x-auto">
          <table className="w-full">
            <thead>
              <tr className="text-left text-xs text-sentinel-text-dim border-b border-sentinel-border">
                <th className="pb-3 font-medium w-8">
                  <input type="checkbox" className="rounded bg-sentinel-panel-light border-sentinel-border" />
                </th>
                <th className="pb-3 font-medium">Report Name</th>
                <th className="pb-3 font-medium">Type</th>
                <th className="pb-3 font-medium">Generated By</th>
                <th className="pb-3 font-medium">Date Generated</th>
                <th className="pb-3 font-medium">Status</th>
                <th className="pb-3 font-medium text-right">Actions</th>
              </tr>
            </thead>
            <tbody>
              {reports.map((report) => {
                const config = typeIcons[report.type] || typeIcons.Executive;
                const Icon = config.icon;
                const isSelected = selectedId === report.id;

                return (
                  <tr
                    key={report.id}
                    onClick={() => onSelectReport(report)}
                    className={`border-b border-sentinel-border/50 cursor-pointer transition-colors ${
                      isSelected
                        ? 'bg-cyan-500/10 border-l-2 border-l-cyan-400'
                        : 'hover:bg-sentinel-panel-light/50'
                    }`}
                  >
                    <td className="py-3">
                      <input
                        type="checkbox"
                        className="rounded bg-sentinel-panel-light border-sentinel-border"
                        onClick={(e) => e.stopPropagation()}
                      />
                    </td>
                    <td className="py-3">
                      <div className="flex items-center gap-2">
                        <Icon className={`w-4 h-4 ${config.color} flex-shrink-0`} />
                        <span className="text-sm text-white whitespace-nowrap">{report.name}</span>
                      </div>
                    </td>
                    <td className="py-3 text-xs text-sentinel-text-dim whitespace-nowrap">{report.type}</td>
                    <td className="py-3 text-xs text-sentinel-text-dim whitespace-nowrap">{report.generatedBy}</td>
                    <td className="py-3 text-xs text-sentinel-text-dim whitespace-nowrap">{report.date}</td>
                    <td className="py-3">
                      <span className={`inline-block px-2 py-0.5 text-[10px] font-medium rounded ${statusStyles[report.status] || statusStyles.Completed}`}>
                        {report.status}
                      </span>
                    </td>
                    <td className="py-3 text-right">
                      <button className="p-1 rounded text-sentinel-text-dim hover:text-white hover:bg-sentinel-panel-light transition-colors">
                        <MoreHorizontal className="w-4 h-4" />
                      </button>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}

      <div className="flex items-center justify-between mt-4 pt-4 border-t border-sentinel-border">
        <p className="text-xs text-sentinel-text-dim">
          Showing <span className="text-white font-medium">1-{reports.length}</span> of{' '}
          <span className="text-white font-medium">{reports.length}</span> reports
        </p>
      </div>
    </div>
  );
};

export default ReportsTable;